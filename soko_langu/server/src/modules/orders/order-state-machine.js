function canonicalizeState(state) {
  if (!state) return ORDER_STATES.AWAITING_SELLER_SHIPPING;
  const normalized = String(state).trim();
  return LEGACY_TO_CANONICAL[normalized.toLowerCase()] || normalized.toUpperCase();
}

class OrderStateMachine {
  constructor(state) {
    this.state = canonicalizeState(state);
  }

  canTransition(toState) {
    return (STATE_TRANSITIONS[this.state] || []).includes(canonicalizeState(toState));
  }

  transition(toState, { actor, reason } = {}) {
    const from = this.state;
    const to = canonicalizeState(toState);
    if (!this.canTransition(to)) throw new Error('INVALID_ORDER_TRANSITION:' + from + '->' + to);
    const allowedActors = TRANSITION_ACTORS[to] || [];
    if (actor && !allowedActors.includes(actor)) {
      throw new Error('INVALID_ORDER_ACTOR:' + actor + '->' + to);
    }
    this.state = to;
    return { from, to, financialRule: STATE_FINANCIAL_RULES[to], actor, reason, timestamp: new Date().toISOString() };
  }

  static canonicalize(state) { return canonicalizeState(state); }
  static getFinancialRule(state) { return STATE_FINANCIAL_RULES[canonicalizeState(state)]; }
  static canReleaseFunds(state) { return STATE_FINANCIAL_RULES[canonicalizeState(state)] === 'SETTLEMENT_AUTHORIZED'; }
}

