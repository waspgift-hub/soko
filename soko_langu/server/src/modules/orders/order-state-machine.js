// States where funds or settlement are under active protection and must not
// be released by an automation without an explicit financial action.
const PROTECTED_STATES = [
  ORDER_STATES.DISPUTED,
  ORDER_STATES.REFUND_PENDING,
];

// Maps pre-V3 status spellings (Firestore-era lowercase rows and the payment/
// courier flows that predate the canonical set) to their canonical value.
// Single canonicalization point: anything entering the machine is normalized
// here, so a guard or transition can never miss on a legacy spelling.
