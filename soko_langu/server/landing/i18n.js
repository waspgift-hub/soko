  function detectLang() {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    const nav = (navigator.language || 'en').toLowerCase().split('-')[0];
    if (SUPPORTED.includes(nav)) return nav;
    return 'en';
  }

  function apply(lang) {
    const dict = DICT[lang] || DICT.en;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.innerHTML = dict[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) el.placeholder = dict[key];
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) el.title = dict[key];
    });
    const body = document.body;
    const titleKey = (body && body.dataset.titleKey) || 'doc_title';
    const title = dict[titleKey];
    if (title) document.title = title;
    const descKey = (body && body.dataset.descKey) || 'doc_desc';
    const desc = dict[descKey];
    if (desc) {
      const meta = document.querySelector('meta[name="description"]');
      if (meta) meta.setAttribute('content', desc);
    }
    document.querySelectorAll('select.lang-select').forEach((sel) => {
      if (sel.value !== lang) sel.value = lang;
    });
    localStorage.setItem(LANG_KEY, lang);
  }

  window.SokoI18n = {
    SUPPORTED, NAMES, DICT,
    detect: detectLang,
    apply,
    t: (lang, key) => (DICT[lang] || DICT.en)[key] || key,
  };

  document.addEventListener('DOMContentLoaded', () => {
    apply(detectLang());
    document.querySelectorAll('select.lang-select').forEach((sel) => {
      sel.addEventListener('change', (e) => apply(e.target.value));
    });
  });
